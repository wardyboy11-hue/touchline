"""Build stretch/data.js + stretch/audio/*.mp3 from tools/stretch/stretches.json.
r95: Alice British female voice (not Tim Cipher). Needs ELEVENLABS_API_KEY for new lines."""
import json,os,sys,math,hashlib,urllib.request,subprocess
R=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VOICE=os.environ.get('STRETCH_VOICE','Xb7hH8MSUJpSbSDYk0k2')  # Alice - Clear, Engaging Educator (British female)
MODEL='eleven_multilingual_v2'
CACHE=os.path.join(R,'tools/stretch/.tts');os.makedirs(CACHE,exist_ok=True)
od=os.path.join(R,'stretch/audio');os.makedirs(od,exist_ok=True)
def tts(text):
    h=hashlib.sha1((VOICE+MODEL+text).encode()).hexdigest()[:16]
    f=os.path.join(CACHE,h+'.mp3')
    if not os.path.exists(f):
        key=os.environ.get('ELEVENLABS_API_KEY')
        if not key: raise SystemExit('ELEVENLABS_API_KEY missing')
        body=json.dumps(dict(text=text,model_id=MODEL,voice_settings=dict(stability=0.45,similarity_boost=0.8,style=0.2,use_speaker_boost=True))).encode()
        rq=urllib.request.Request(f'https://api.elevenlabs.io/v1/text-to-speech/{VOICE}?output_format=mp3_44100_128',
          data=body,headers={'xi-api-key':key,'content-type':'application/json','accept':'audio/mpeg'})
        for n in range(4):
            try:
                open(f+'.tmp','wb').write(urllib.request.urlopen(rq,timeout=120).read());os.rename(f+'.tmp',f);break
            except Exception as e:
                if n==3: raise
                import time;time.sleep(3+n*4)
    return f
def dur(f):
    return float(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0',f]))
def put(name,text):
    c=tts(text);o=os.path.join(od,name+'.mp3');open(o,'wb').write(open(c,'rb').read());return round(dur(o),2)
D=json.load(open(os.path.join(R,'tools/stretch/stretches.json')))
out={'welcome':{'a':'welcome','d':put('welcome',D['welcome'])},
     'finish':{'a':'finish','d':put('finish',D['finish'])},
     'count':{'a':'count','d':put('count',D['count'])},
     'switch':{'a':'switch','d':put('switch',D.get('switch','And switch.'))},
     'relax':{'a':'relax','d':put('relax',D.get('relax','Relax. Take a slow breath out. Next stretch coming up.'))},
     'voice':{'name':'Alice','id':VOICE,'accent':'British female'},
     'items':[]}
for n,it in enumerate(D['items']):
    a='s%02d'%n;d=put(a,it['vo']);x=dict(it);x['a']=a;x['ad']=d
    x['intro']=max(8,math.ceil(d+1.2));x['secs']=max(15,int(x.get('secs') or 30))
    out['items'].append(x)
open(os.path.join(R,'stretch/data.js'),'w').write('/* generated by tools/stretch/build.py (Alice r95) */\nvar STRETCH='+json.dumps(out,ensure_ascii=False)+';\n')
# cool-down total with 15s rests between items
items=out['items'];rest=15*(len(items)-1) if len(items)>1 else 0
t=out['welcome']['d']+1+sum(i['intro']+i['secs'] for i in items)+rest+out['finish']['d']+1
print('voice',VOICE,'Alice')
print('total %d:%02d (with rests)'%(t//60,t%60))
for i in out['items']:print(i['a'],i['name'],i['side'],i['intro'],i['secs'],i['ad'])
