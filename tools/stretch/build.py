"""Build stretch/data.js + stretch/audio/*.mp3 from tools/stretch/stretches.json.
Same ElevenLabs voice and settings as tools/anim/build.py. Needs ELEVENLABS_API_KEY only for new lines."""
import json,os,sys,math
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','anim'))
R=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import importlib.util
spec=importlib.util.spec_from_file_location('ab',os.path.join(R,'tools/anim/build.py'))
src=open(os.path.join(R,'tools/anim/build.py')).read().split('HEAD=open')[0]
ns={'__file__':os.path.join(R,'tools/anim/build.py')};exec(src,ns);tts,dur=ns['tts'],ns['dur']
D=json.load(open(os.path.join(R,'tools/stretch/stretches.json')))
od=os.path.join(R,'stretch/audio');os.makedirs(od,exist_ok=True)
def put(name,text):
    c=tts(text);o=os.path.join(od,name+'.mp3');open(o,'wb').write(open(c,'rb').read());return round(dur(o),2)
out={'welcome':{'a':'welcome','d':put('welcome',D['welcome'])},'finish':{'a':'finish','d':put('finish',D['finish'])},
     'count':{'a':'count','d':put('count',D['count'])},'switch':{'a':'switch','d':put('switch',D['switch'])},'items':[]}
for n,it in enumerate(D['items']):
    a='s%02d'%n;d=put(a,it['vo']);x=dict(it);x['a']=a;x['ad']=d;x['intro']=max(15,math.ceil(d+1.5));out['items'].append(x)
open(os.path.join(R,'stretch/data.js'),'w').write('/* generated by tools/stretch/build.py */\nvar STRETCH='+json.dumps(out,ensure_ascii=False)+';\n')
t=out['welcome']['d']+1+sum(i['intro']+i['secs'] for i in out['items'])
print('total %d:%02d'%(t//60,t%60));[print(i['a'],i['name'],i['side'],i['intro'],i['secs'],i['ad']) for i in out['items']]
