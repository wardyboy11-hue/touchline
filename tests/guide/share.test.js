const par=fs.readFileSync(path.join(root,'parents.html'),'utf8');
const app=fs.readFileSync(path.join(root,'coach/app.js'),'utf8');
const idx=fs.readFileSync(path.join(root,'coach/index.html'),'utf8');
assert.ok(/share\.js\?v=105/.test(fam)&&/share\.js\?v=105/.test(par)&&/share\.js\?v=105/.test(idx));
