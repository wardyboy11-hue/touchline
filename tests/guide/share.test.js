const fsw=fs.readFileSync(path.join(root,'fsw.js'),'utf8');
assert.ok(/share\.js\?v=105/.test(sw)&&/share\.js\?v=105/.test(fsw));
assert.ok(/touchline-shell-v105/.test(sw));
